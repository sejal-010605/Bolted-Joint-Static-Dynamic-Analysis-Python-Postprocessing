PHASE_TOLERANCE_DEG = 12.0

PHASE_TOLERANCE = (
    PHASE_TOLERANCE_DEG * math.pi / 180.0
)

CONTACT_RADIUS_TOLERANCE = 0.08

CONTACT_TOLERANCE = 1.0e-6




def percentile(values, p):

    values = sorted(values)

    if len(values) == 1:
        return values[0]

    position = (
        p / 100.0
    ) * (len(values) - 1)

    lower = int(
        math.floor(position)
    )

    upper = int(
        math.ceil(position)
    )

    if lower == upper:
        return values[lower]

    fraction = position - lower

    return (
        values[lower]
        +
        fraction
        *
        (
            values[upper]
            -
            values[lower]
        )
    )


def wrap_angle(angle):

    while angle > math.pi:
        angle -= 2.0 * math.pi

    while angle < -math.pi:
        angle += 2.0 * math.pi

    return angle



# DETECT HELIX

def detect_helix(nodes, labels):

    best_sign = None
    best_phase = None
    best_population = 0

    for sign in [1.0, -1.0]:

        counts = [0] * PHASE_BINS

        for label in labels:

            x, y, z, radius, theta = (
                nodes[label]
            )

            phase = (
                theta
                -
                sign
                *
                2.0
                *
                math.pi
                *
                (
                    (z - Z_ZERO)
                    /
                    PITCH
                )
            )

            phase = (
                phase
#                 %
                (2.0 * math.pi)
            )

            index = int(
                PHASE_BINS
                *
                phase
                /
                (2.0 * math.pi)
            )

            if index >= PHASE_BINS:

                index = (
                    PHASE_BINS - 1
                )

            counts[index] += 1

        population = max(counts)

        if population == 0:
            continue

        index = counts.index(
            population
        )

        phase = (
            (index + 0.5)
            *
            2.0
            *
            math.pi
            /
            PHASE_BINS
        )

        if population > best_population:

            best_population = population
            best_sign = sign
            best_phase = phase

    return (
        best_sign,
        best_phase,
        best_population
    )


# SELECT HELICAL NODES

def select_helix(
    nodes,
    labels,
    sign,
    phase
):

    selected = set()

    for label in labels:

        x, y, z, radius, theta = (
            nodes[label]
        )

        current_phase = (
            theta
            -
            sign
            *
            2.0
            *
            math.pi
            *
            (
                (z - Z_ZERO)
                /
                PITCH
            )
        )

        current_phase = (
            current_phase
#             %
            (2.0 * math.pi)
        )

        difference = abs(
            wrap_angle(
                current_phase
                -
                phase
            )
        )

        if (
            difference
            <=
            PHASE_TOLERANCE
        ):

            selected.add(label)

    return selected


